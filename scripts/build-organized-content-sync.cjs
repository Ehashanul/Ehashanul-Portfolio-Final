// Generate the reviewed SQL update from the same content used by the website.
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'node_modules/.cache/portfolio-content.cjs');
esbuild.buildSync({stdin:{contents:"export { projects } from './src/data/projects.js';",resolveDir:root},bundle:true,platform:'node',format:'cjs',outfile:output,logLevel:'error'});
const {projects} = require(output);
const content = projects.map(project => {
  const copy = {...project};
  for(const key of ['hideCardImage','hideCardTitle','hideCardSubtitle','liveUrl']) delete copy[key];
  return copy;
});
const legacy = ['overview','contributions','challenge','goals','research','process','decisions','gallery-intro','gallery','design-gallery','validation','outcomes','lessons','project-results','journey-visual','onboarding-visual','feature-access-visual'];
const source = fs.readFileSync(path.join(root,'src/data/caseStudyCopy.js'),'utf8');
const generated = source.match(/const generatedIds = new Set\(\[([^]*?)\]\);/)[1].match(/'([^']+)'/g).map(value=>value.slice(1,-1));
const managed = [...new Set([...legacy,...generated,...content.flatMap(project=>project.sections.map(section=>section.id))])];
const initial = fs.readFileSync(path.join(root,'supabase/migrations/001_portfolio.sql'),'utf8');
const publish = initial.slice(initial.indexOf('create function public.publish_project'),initial.indexOf('create function public.unpublish_project')).replace('create function public.publish_project','create or replace function public.publish_project');
const sql=`-- Run this update in the existing project's Supabase SQL Editor, not 001 again.
-- Generated by: node scripts/build-organized-content-sync.cjs
-- Stores concise case studies and adds missing requested project entries.
-- Retains custom/hidden draft blocks, public custom blocks, and publication status.
begin;
select pg_advisory_xact_lock(hashtext('portfolio-case-study-content-sync'));

${publish}

do $sync$
declare
  prepared jsonb := $portfolio_payload$${JSON.stringify(content,null,2)}$portfolio_payload$::jsonb;
  managed_ids jsonb := $managed_ids$${JSON.stringify(managed)}$managed_ids$::jsonb;
  entry jsonb;
  project_id text;
  prior public.project_drafts;
  patch jsonb;
  prepared_sections jsonb;
  draft_sections jsonb;
begin
  for entry in select value from jsonb_array_elements(prepared) loop
    project_id := entry->>'id';
    select * into prior from public.project_drafts where id = project_id for update;
    if not found then
      insert into public.project_drafts(id,content) values(project_id, entry - 'id');
      insert into public.published_projects(id,content,sort_order) values(project_id,entry - 'id',coalesce((entry->>'sortOrder')::integer,0));
      select * into prior from public.project_drafts where id = project_id for update;
    end if;
    if prior.deleted_at is not null then continue; end if;
    patch := entry - 'id' - 'sections' - 'sortOrder' - 'featured';
    select coalesce(jsonb_agg(
      case when exists (
        select 1 from jsonb_array_elements(coalesce(prior.content->'sections','[]'::jsonb)) old
        where old->>'id' = fresh->>'id' and old->>'hidden' = 'true'
      ) then fresh || '{"hidden":true}'::jsonb else fresh end order by position
    ),'[]'::jsonb) into prepared_sections
    from jsonb_array_elements(entry->'sections') with ordinality as template(fresh,position);

    select prepared_sections || coalesce(jsonb_agg(old order by position),'[]'::jsonb) into draft_sections
    from jsonb_array_elements(coalesce(prior.content->'sections','[]'::jsonb)) with ordinality as original(old,position)
    where not (managed_ids ? (old->>'id'))
       or (old->>'hidden' = 'true' and not exists (
         select 1 from jsonb_array_elements(entry->'sections') fresh where fresh->>'id' = old->>'id'
       ));
    update public.project_drafts set content = prior.content || patch || jsonb_build_object('sections',draft_sections)
    where id = project_id;

    -- Build the public snapshot from the prepared copy plus already-public
    -- custom blocks. Never copy an unpublished custom block out of a draft.
    update public.published_projects published set
      content = published.content || patch || jsonb_build_object('sections',
        coalesce((select jsonb_agg(section order by position)
          from jsonb_array_elements(prepared_sections) with ordinality as visible(section,position)
          where coalesce(section->>'hidden','false') <> 'true'),'[]'::jsonb)
        || coalesce((select jsonb_agg(old order by position)
          from jsonb_array_elements(coalesce(published.content->'sections','[]'::jsonb)) with ordinality as original(old,position)
          where not (managed_ids ? (old->>'id'))
            and coalesce(old->>'hidden','false') <> 'true'),'[]'::jsonb)
      ), published_at = now()
    where published.id = project_id;
  end loop;
end;
$sync$;
commit;
`;
fs.writeFileSync(path.join(root,'supabase/migrations/004_organized_case_studies.sql'),sql);
console.log('Prepared SQL for organized case studies and requested projects.');
